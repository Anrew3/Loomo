import Foundation

/// Writes a WireViz YAML file (https://github.com/wireviz/WireViz) so that
/// `wireviz harness.yml` can render a connection diagram.
/// Each wire becomes a one-core cable; splices become one-pin connectors.
public enum WireVizExport {
    public static func yaml(for h: Harness, analysis: HarnessAnalysis? = nil) -> String {
        let analysis = analysis ?? HarnessAnalysis(h)
        let wires = h.wires.filter { $0.from != .unassigned && $0.to != .unassigned }
        var out = "# Generated by Loomo — \(h.name) rev \(h.revision)\n"
        out += "metadata:\n  title: \(quote(h.name))\n  revision: \(quote(h.revision))\n\n"

        out += "connectors:\n"
        for c in h.connectors {
            out += "  \(c.id):\n"
            out += "    type: \(quote(c.name.isEmpty ? "Connector" : c.name))\n"
            out += "    subtype: \(c.gender.rawValue)\n"
            out += "    pinlabels: [\(c.cavities.map { quote($0.signal ?? $0.label) }.joined(separator: ", "))]\n"
            if let p = c.part {
                out += "    mpn: \(quote(p.mpn))\n    manufacturer: \(quote(p.manufacturer))\n"
            }
        }
        for s in h.splices {
            out += "  \(s.id):\n    type: \(quote("Splice (\(s.kind.rawValue))"))\n    pincount: 1\n"
        }

        out += "\ncables:\n"
        for w in wires {
            let color = w.color.base + (w.color.stripe ?? "")
            out += "  \(w.id):\n"
            out += "    wirecount: 1\n"
            out += "    gauge: \(quote(w.size.awg.map { "\($0) AWG" } ?? String(format: "%g mm2", w.size.crossSectionMM2)))\n"
            out += "    colors: [\(color)]\n"
            if let mm = analysis.routes[w.id]?.lengthMM {
                out += String(format: "    length: %.3f\n", mm / 1000)
            }
            if let signal = w.signal { out += "    wirelabels: [\(quote(signal))]\n" }
            out += "    category: bundle\n"
        }

        out += "\nconnections:\n"
        for w in wires {
            out += "  -\n    - \(ref(w.from))\n    - \(w.id): [1]\n    - \(ref(w.to))\n"
        }
        return out
    }

    private static func ref(_ e: Endpoint) -> String {
        switch e {
        case let .pin(c, cav): return "\(c): [\(Int(cav).map(String.init) ?? quote(cav))]"
        case let .splice(s): return "\(s): [1]"
        case .unassigned: return ""
        }
    }

    private static func quote(_ s: String) -> String {
        "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}
